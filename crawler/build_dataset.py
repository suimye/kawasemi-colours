#!/usr/bin/env python3
"""
build_dataset.py  -- assemble the curated kawasemi_colors dataset.

This turns the CURATED records below (each derived from a verified open-access
PMC figure caption or a species' well-documented plumage colour) into:

    ../data/dataset.jsonl     one JSON object per SEM/TEM panel  (contract schema)
    ../data/dataset.csv       flattened convenience copy
    ../data/images/*.png      one image per record

Images
------
Real PMC figure binaries are gated behind a browser check (reCAPTCHA) and were
NOT fetchable in the build environment, so every image generated by this script
is a MODEL-GENERATED SYNTHETIC PROXY based on parameters implied by
each record's colour, using the contract's relation:

    peak_nm ~= 2 * n_eff * d
    n_eff   = pore_fraction*1.0 + (1 - pore_fraction)*1.56   (keratin)

=> characteristic centre-to-centre spacing  d = peak_nm / (2 * n_eff).

Each record carries  real_image: false  and  notes containing
"synthetic_proxy" so a synthetic panel is NEVER mistaken for a real figure.
If you later obtain real pixels, drop them into data/images/ under the same
image_file name and set real_image: true for that record.

Run:
    python build_dataset.py
"""


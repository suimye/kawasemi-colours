# --------------------------------------------------------------------------- #
# Physics helpers
# --------------------------------------------------------------------------- #

def n_eff(pore_fraction: float) -> float:
    return pore_fraction * 1.0 + (1.0 - pore_fraction) * N_KERATIN


def char_length_nm(peak_nm: float | None, pore_fraction: float) -> float | None:
    """Invert peak ~= 2*n_eff*d  ->  d = peak / (2 n_eff)."""
    if peak_nm is None:
        return None
    return peak_nm / (2.0 * n_eff(pore_fraction))


# --------------------------------------------------------------------------- #
# Synthetic SEM-proxy generator
# --------------------------------------------------------------------------- #

def render_spongy(px: int, spacing_px: float, pore_fraction: float,
                  seed: int) -> Image.Image:
    """Quasi-ordered spongy network: jittered pores on a lattice, then
    threshold to a two-phase (keratin/air) grayscale SEM look."""
    rng = random.Random(seed)
    hi = 4
    big = px * hi
    img = Image.new("L", (big, big), 165)  # keratin matrix (mid gray)
    draw = ImageDraw.Draw(img)
    s = spacing_px * hi
    r = s * (0.30 + 0.35 * pore_fraction)  # pore radius grows with porosity
    jitter = s * (0.18 + 0.5 * pore_fraction)  # disorder grows with porosity
    y = -s
    row = 0
    while y < big + s:
        offset = (s / 2) if row % 2 else 0
        x = -s + offset
        while x < big + s:
            cx = x + rng.uniform(-jitter, jitter)
            cy = y + rng.uniform(-jitter, jitter)
            rr = r * rng.uniform(0.8, 1.2)
            draw.ellipse([cx - rr, cy - rr, cx + rr, cy + rr], fill=40)  # air pore
            x += s
        y += s * 0.87
        row += 1
    img = img.resize((px, px), Image.LANCZOS)
    img = img.filter(ImageFilter.GaussianBlur(0.6))
    # add mild noise for micrograph texture
    noise = Image.effect_noise((px, px), 18)
    img = Image.blend(img, noise, 0.10)
    return img


def render_melanosome(px: int, spacing_px: float, seed: int) -> Image.Image:
    """Ordered melanosome array: bright rods/spheres on a dark keratin bg,
    laid out in near-regular layers (iridescent look)."""
    rng = random.Random(seed)
    hi = 4
    big = px * hi
    img = Image.new("L", (big, big), 55)  # dark keratin background
    draw = ImageDraw.Draw(img)
    s = spacing_px * hi
    r = s * 0.40
    jitter = s * 0.10  # highly ordered
    y = -s
    row = 0
    while y < big + s:
        offset = (s / 2) if row % 2 else 0
        x = -s + offset
        while x < big + s:
            cx = x + rng.uniform(-jitter, jitter)
            cy = y + rng.uniform(-jitter, jitter)
            draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=210)  # melanosome
            draw.ellipse([cx - r * 0.4, cy - r * 0.4,
                          cx + r * 0.4, cy + r * 0.4], fill=120)  # hollow core
            x += s
        y += s * 0.9
        row += 1
    img = img.resize((px, px), Image.LANCZOS)
    img = img.filter(ImageFilter.GaussianBlur(0.5))
    noise = Image.effect_noise((px, px), 14)
    img = Image.blend(img, noise, 0.08)
    return img


def add_scalebar(img: Image.Image, label: str) -> Image.Image:
    img = img.convert("L")
    d = ImageDraw.Draw(img)
    w, h = img.size
    bar_w = int(w * 0.22)
    x0, y0 = int(w * 0.06), int(h * 0.92)
    d.rectangle([x0, y0, x0 + bar_w, y0 + 6], fill=255)
    d.text((x0, y0 - 14), label, fill=255)
    return img


def make_image(rec: dict, d_nm: float | None, out_path: str) -> None:
    px = 320
    # map physical spacing to pixels; if unknown, use a nominal spongy spacing
    d = d_nm if d_nm else 160.0
    # choose a pixel spacing so the field shows ~12-16 repeat units
    spacing_px = px / 14.0
    seed = abs(hash(rec["sfx"])) % (2**31)
    if rec["structure"] == "spongy":
        img = render_spongy(px, spacing_px, rec["pore"], seed)
    else:
        img = render_melanosome(px, spacing_px, seed)
    label = f"~{int(round(d))} nm period (proxy)"
    img = add_scalebar(img, label)
    img.save(out_path)


# --------------------------------------------------------------------------- #
# Assemble
# --------------------------------------------------------------------------- #

def main() -> None:
    os.makedirs(IMAGES, exist_ok=True)
    jsonl_rows, csv_rows = [], []

    for rec in RECORDS:
        src = SOURCES[rec["pmcid"]]
        pmcid_field = rec["pmcid"] if rec["pmcid"] != "SPECIES_REF" else "n/a"
        rid = (rec["pmcid"] if rec["pmcid"] != "SPECIES_REF"
               else "SPECIESREF") + "_" + rec["sfx"]
        image_file = f"images/{rid}.png"
        d_nm = char_length_nm(rec["peak"], rec["pore"])
        color_name = rec["color"]
        hexv = COLOR_HEX.get(color_name, "#808080")
        srgb = hex_to_rgb(hexv)

        notes = (f"synthetic_proxy; {rec['note']}; "
                 f"color_source={rec['csrc']}; "
                 f"n_eff={n_eff(rec['pore']):.3f}")

        obj = {
            "id": rid,
            "image_file": image_file,
            "real_image": False,
            "source": {
                "pmcid": pmcid_field,
                "doi": src["doi"],
                "title": src["title"],
                "license": src["license"],
                "url": src["url"],
                "figure": rec["figure"],
            },
            "species": rec["species"],
            "common_name": rec["common"],
            "structure_type": rec["structure"],
            "color": {
                "name": color_name,
                "hex": hexv,
                "srgb": srgb,
                "peak_nm": rec["peak"],
            },
            "scale": {
                "bar_um": rec["scale"],
                "px_per_um": None,
            },
            "notes": notes,
        }
        jsonl_rows.append(obj)

        # render synthetic proxy
        make_image(rec, d_nm, os.path.join(DATA, f"{image_file}"))

        csv_rows.append({
            "id": rid,
            "image_file": image_file,
            "real_image": False,
            "pmcid": pmcid_field,
            "doi": src["doi"],
            "title": src["title"],
            "license": src["license"],
            "url": src["url"],
            "figure": rec["figure"],
            "species": rec["species"],
            "common_name": rec["common"],
            "structure_type": rec["structure"],
            "color_name": color_name,
            "color_hex": hexv,
            "color_srgb": "|".join(str(c) for c in srgb),
            "peak_nm": rec["peak"] if rec["peak"] is not None else "",
            "char_length_nm": f"{d_nm:.1f}" if d_nm else "",
            "pore_fraction": rec["pore"],
            "scale_bar_um": rec["scale"] if rec["scale"] is not None else "",
            "notes": notes,
        })

    with open(os.path.join(DATA, "dataset.jsonl"), "w", encoding="utf-8") as fh:
        for obj in jsonl_rows:
            fh.write(json.dumps(obj, ensure_ascii=False) + "\n")

    with open(os.path.join(DATA, "dataset.csv"), "w", newline="",
              encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(csv_rows[0].keys()))
        w.writeheader()
        w.writerows(csv_rows)

    real = sum(1 for o in jsonl_rows if o["real_image"])
    print(f"Wrote {len(jsonl_rows)} records "
          f"({real} real, {len(jsonl_rows) - real} synthetic).")
